public class SumaEntersFixos { 
    public static void main(String[] args)  {
        /**Introdueixo unes variables i poso un nombre fixe per cadascuna y despres les sumo */

       int num1, num2, res;
         num1 = 94;
         num2 = 46;

        res = (num1 + num2);
        /**Una vegada sumades es posa el resultat */

        System.out.printf("El resultado de %d + %d = %d", num1, num2, res);
    }
}